/**
 * gerstnerPoint(x, t): ผิวน้ำแบบ Gerstner 4 ระลอก (N = 4) มุมมองด้านข้าง สำหรับ Canvas 2D
 *
 * ในฟังก์ชันนี้ ทุกระลอกขยับจุดทั้งแนวนอน (x) และแนวตั้ง (y):
 *   θᵢ  = kᵢ·Dxᵢ·x − ωᵢ·t + φᵢ                 (ภาพตัดขวางคือเส้น z = 0 จึงไม่มีพจน์ kᵢ·Dzᵢ·z)
 *   x'  = x + Σ qᵢ·Aᵢ·Dxᵢ·cos θᵢ                (แนวนอน: ดึงจุดเข้าหายอดคลื่น)
 *   y   =     Σ Aᵢ·sin θᵢ                       (แนวตั้ง: ความสูงเหนือระดับน้ำนิ่ง ค่าบวก = ขึ้น)
 *
 * ทำไมยอดแหลมและท้องกว้าง:
 *   dx'/dx = 1 − Σ qᵢ·kᵢ·Aᵢ·Dxᵢ²·sin θᵢ
 *   ที่ยอดคลื่น sin θ = +1 → dx'/dx < 1 → จุดถูกบีบเข้าหากัน → ยอดแหลม
 *   ที่ท้องคลื่น sin θ = −1 → dx'/dx > 1 → จุดถูกยืดออก → ท้องกว้างและแบน
 *
 * การ normalize Q (กันผิวน้ำม้วนเป็นลูป):
 *   qᵢ = Qᵢ·(Aᵢ/ΣA) / (kᵢ·Aᵢ)  →  Σ qᵢ·kᵢ·Aᵢ·Dxᵢ² ≤ Σ Qᵢ·Aᵢ/ΣA ≤ 1
 *   ผลคือ dx'/dx ≥ 0 เสมอ (ไม่มีลูป) และระลอกใหญ่ได้ความแหลมมากกว่าระลอกเล็ก
 *
 * วิธีวาดบน Canvas (แกน y ของ canvas ชี้ลง จึงต้องกลับเครื่องหมาย):
 *   ctx.beginPath();
 *   for (let x = -60; x <= canvas.width + 60; x += 2) {   // เผื่อขอบเพราะ x' ขยับได้ประมาณ ±40px
 *     const [xp, h] = gerstnerPoint(x, t);
 *     x === -60 ? ctx.moveTo(xp, SEA_LEVEL - h) : ctx.lineTo(xp, SEA_LEVEL - h);
 *   }
 *   ctx.stroke();
 *
 * @param {number} x  ตำแหน่งแนวนอนตั้งต้นของจุดบนผิวน้ำ (พิกเซล)
 * @param {number} t  เวลา (วินาที)
 * @returns {[number, number]} [x', y]  โดย x' คือตำแหน่งหลังขยับ (px) และ y คือความสูงเทียบ y = 0 (px, บวก = ขึ้น)
 */
function gerstnerPoint(x, t) {
  // ===================== ค่าคงที่ =====================
  // N = 4 ระลอก
  // มาตราส่วน: 1 m = 50 px → g = 9.81 × 50 = 490.5 px/s²
  // ω มาจากสูตรคลื่นน้ำลึก ω = √(g·k) โดย k = 2π/λ (คำนวณไว้ก่อนแล้วใส่เป็นตัวเลขตายตัว):
  //   λ=320 → k=0.019635 → ω=3.1034 rad/s
  //   λ=190 → k=0.033069 → ω=4.0275 rad/s
  //   λ=115 → k=0.054636 → ω=5.1768 rad/s
  //   λ= 70 → k=0.089760 → ω=6.6353 rad/s
  // dir = ทิศที่ระลอกเดินทางบนผิวน้ำ (องศา วัดจากแกน +x) และ Dx = cos(dir)
  // Q   = steepness 0–1 (1 = ยอดแหลมสุดจนเกือบเป็นจุด)
  // φ   = phase เริ่มต้น (rad)
  // ΣA  = 14 + 8 + 4.5 + 2.5 = 29 px
  const N = 4;
  const SUM_A = 29.0;
  const WAVES = [
    //  A (px)    λ (px)   dir (°)    ω (rad/s)    Q           φ (rad)
    { A: 14.0, L: 320, dir:   0, w: 3.1034, Q: 0.90, phi: 0.0 }, // คลื่นหลัก ไปทาง +x
    { A:  8.0, L: 190, dir:  18, w: 4.0275, Q: 0.80, phi: 1.7 }, // เฉียงเล็กน้อย
    { A:  4.5, L: 115, dir: -32, w: 5.1768, Q: 0.70, phi: 4.1 }, // เฉียงอีกฝั่ง
    { A:  2.5, L:  70, dir: 200, w: 6.6353, Q: 0.60, phi: 2.6 }, // ระลอกเล็กวิ่งสวนทาง (Dx ≈ −0.94)
  ];
  // ====================================================

  let xp = x;  // x' หลังขยับ
  let y = 0;   // ความสูงผิวน้ำ

  for (let i = 0; i < N; i++) {
    const { A, L, dir, w, Q, phi } = WAVES[i];
    const k = (2 * Math.PI) / L;                 // wavenumber (rad/px)
    const Dx = Math.cos((dir * Math.PI) / 180);  // ส่วนของทิศคลื่นที่อยู่บนแกน x
    const theta = k * Dx * x - w * t + phi;      // phase ของจุดนี้
    const q = (Q * (A / SUM_A)) / (k * A);       // steepness ที่ normalize แล้ว (กันลูป)

    xp += q * A * Dx * Math.cos(theta);          // ขยับแนวนอน (ทำให้ยอดแหลม)
    y  += A * Math.sin(theta);                   // ขยับแนวตั้ง
  }

  return [xp, y];
}
